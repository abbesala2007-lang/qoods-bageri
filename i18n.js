const LANG_KEY = "qoods_lang";
const currentLang = () => localStorage.getItem(LANG_KEY) || "sv";
const t = key => { const l = currentLang(); return (T[l] && T[l][key] != null) ? T[l][key] : (T.en[key] != null ? T.en[key] : key); };
const pName = id => { const l = currentLang(); return (P[id] && P[id][l] && P[id][l].name) || (P[id] && P[id].en.name) || id; };
const pDesc = id => { const l = currentLang(); return (P[id] && P[id][l] && P[id][l].desc) || (P[id] && P[id].en.desc) || ""; };

function applyLang(lang){
  localStorage.setItem(LANG_KEY, lang);
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach(el => { el.innerHTML = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll("[data-lang]").forEach(b => b.classList.toggle("active", b.dataset.lang === lang));
  if (typeof window.onLangApplied === "function") window.onLangApplied(lang);
}
function setLang(lang){ applyLang(lang); }

/* ---- theme ---- */
const THEME_KEY = "qoods_theme";
const currentTheme = () => localStorage.getItem(THEME_KEY) || "light";
function applyTheme(th){
  localStorage.setItem(THEME_KEY, th);
  document.documentElement.setAttribute("data-theme", th);
  document.querySelectorAll("[data-theme-toggle]").forEach(b => b.textContent = th === "dark" ? "☀" : "☾");
}
function toggleTheme(){ applyTheme(currentTheme() === "dark" ? "light" : "dark"); }

document.addEventListener("DOMContentLoaded", () => { applyTheme(currentTheme()); applyLang(currentLang()); });
